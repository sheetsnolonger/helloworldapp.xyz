function requireLogin(req, res, next) {
    if (!req.session.userId) {
        return res.redirect("/login");
    }

    next();
}

function requireAdmin(req, res, next) {
    if (!req.session.adminAuthenticated) {
        return res.redirect("/" + adminPath);
    }

    next();
}

async function currentUser(req) {
    if (!req.session.userId) {
        return null;
    }

    return await db.prepare(`
        select
            id,
            username,
            bio,
            created_at
        from users
        where id = ?
    `).get(req.session.userId);
}

async function initializeExtraTables() {
    await db.pool.query(`
        create table if not exists communities (
            id integer generated by default as identity primary key,
            name varchar(50) not null unique,
            description varchar(300) not null default '',
            created_by integer references users(id) on delete set null,
            created_at timestamptz not null default current_timestamp
        );

        create table if not exists community_members (
            id integer generated by default as identity primary key,
            community_id integer not null references communities(id) on delete cascade,
            user_id integer not null references users(id) on delete cascade,
            created_at timestamptz not null default current_timestamp,
            unique(community_id, user_id)
        );

        create index if not exists communities_created_at_idx
            on communities(created_at desc);

        create index if not exists community_members_community_idx
            on community_members(community_id);

        create index if not exists community_members_user_idx
            on community_members(user_id);
    `);

    console.log("extra database tables initialized.");
}

