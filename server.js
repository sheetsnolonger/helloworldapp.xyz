app.get("/feed", requireLogin, async (req, res) => {
    try {
        const user = await currentUser(req);

        if (!user) {
            return res.redirect("/login");
        }

        const posts = await db.prepare(`
            select
                posts.*,
                users.username,

                (
                    select count(*)
                    from likes
                    where likes.post_id = posts.id
                ) as likes,

                (
                    select count(*)
                    from comments
                    where comments.post_id = posts.id
                ) as comments,

                exists (
                    select 1
                    from likes
                    where likes.post_id = posts.id
                    and likes.user_id = ?
                ) as liked

            from posts

            join users
                on users.id = posts.user_id

            order by posts.created_at desc

            limit 100
        `).all(user.id);

        const getComments = db.prepare(`
            select
                comments.id,
                comments.content,
                comments.created_at,
                users.username

            from comments

            join users
                on users.id = comments.user_id

            where comments.post_id = ?

            order by comments.created_at asc
        `);

        for (const post of posts) {
            post.comment_list =
                await getComments.all(post.id);
        }

        const communities = await db.prepare(`
            select
                communities.*,
                users.username as creator,

                (
                    select count(*)
                    from community_members
                    where community_members.community_id =
                        communities.id
                ) as members

            from communities

            left join users
                on users.id = communities.created_by

            order by communities.created_at desc
        `).all();

        res.render("feed", {
            user,
            posts,
            communities
        });
    } catch (error) {
        console.error("feed error:", error);

        res.status(500).send("internal server error.");
    }
});

